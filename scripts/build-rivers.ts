/**
 * Builds src/data/geo/rivers.data.ts: the major rivers ground forces must bridge, as simplified
 * [lon, lat] polylines from Natural Earth 10m rivers and lake centrelines (public domain). The
 * Imjin, which Natural Earth omits at 10m, is traced by hand.
 *
 * Run: npx tsx scripts/build-rivers.ts   (the download is cached in .cache/)
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const CACHE = path.join(ROOT, '.cache');
const OUT = path.join(ROOT, 'src/data/geo/rivers.data.ts');
const NAME = 'ne_10m_rivers_lake_centerlines';
const URL = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/${NAME}.geojson`;

type Line = [number, number][];
/** Natural Earth name, and the box [west, south, east, north] that picks the right river when names repeat. */
const PICK: { river: string; ne: string; box?: [number, number, number, number] }[] = [
  { river: 'Dnipro', ne: 'Dnieper' },
  { river: 'Siverskyi Donets', ne: 'Donets', box: [34, 47, 42, 52] },
  { river: 'Vistula', ne: 'Vistula' },
  { river: 'Oder', ne: 'Oder' },
  { river: 'Danube', ne: 'Danube' },
  { river: 'Rhine', ne: 'Rhine' },
  { river: 'Rhine', ne: 'Rhein' },
  { river: 'Yalu', ne: 'Yalu' },
  { river: 'Han', ne: 'Han', box: [126, 36.8, 128.5, 38] },
  { river: 'Indus', ne: 'Indus' },
  { river: 'Sutlej', ne: 'Sutlej' },
  { river: 'Chenab', ne: 'Chenab' },
  { river: 'Ravi', ne: 'Ravi' },
  { river: 'Jhelum', ne: 'Jhelum' },
  { river: 'Amur', ne: 'Amur' },
  { river: 'Yangtze', ne: 'Yangtze' },
];

/** Imjin, from the Cheorwon plain through Yeoncheon and Jeokseong to the Han estuary at Munsan; hand-traced, ~5 km accuracy. */
const IMJIN: Line = [[127.35, 38.55], [127.2, 38.3], [127.07, 38.1], [126.92, 37.95], [126.78, 37.87], [126.68, 37.76]];

/** Simplification tolerance in degrees: well under the half-degree cells rivers are tested against. */
const TOLERANCE = 0.02;

function simplify(line: Line, tol: number): Line {
  if (line.length < 3) return line;
  const keep = new Uint8Array(line.length);
  keep[0] = keep[line.length - 1] = 1;
  const stack: [number, number][] = [[0, line.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop()!;
    const [ax, ay] = line[a], [bx, by] = line[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-12;
    let worst = -1, far = 0;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * (line[i][0] - ax) - dx * (line[i][1] - ay)) / len;
      if (d > far) { far = d; worst = i; }
    }
    if (far > tol) {
      keep[worst] = 1;
      stack.push([a, worst], [worst, b]);
    }
  }
  return line.filter((_, i) => keep[i]);
}

async function main() {
  fs.mkdirSync(CACHE, { recursive: true });
  const file = path.join(CACHE, `${NAME}.geojson`);
  if (!fs.existsSync(file) || !fs.statSync(file).size) {
    console.log('fetching', URL);
    const res = await fetch(URL);
    if (!res.ok) throw new Error(`${URL}: ${res.status}`);
    fs.writeFileSync(file, await res.text());
  }
  const ne = JSON.parse(fs.readFileSync(file, 'utf8')) as { features: { properties: Record<string, string | null>; geometry: { type: string; coordinates: unknown } }[] };
  const rivers = new Map<string, Line[]>();
  for (const f of ne.features) {
    const name = f.properties.name_en ?? f.properties.name;
    const pick = PICK.find((p) => p.ne === name);
    if (!pick) continue;
    const lines = (f.geometry.type === 'LineString' ? [f.geometry.coordinates] : f.geometry.coordinates) as Line[];
    for (const line of lines) {
      const [w, s, e, n] = pick.box ?? [-180, -90, 180, 90];
      if (!line.some(([x, y]) => x >= w && x <= e && y >= s && y <= n)) continue;
      const out = simplify(line, TOLERANCE).map(([x, y]) => [Math.round(x * 100) / 100, Math.round(y * 100) / 100] as [number, number]);
      (rivers.get(pick.river) ?? rivers.set(pick.river, []).get(pick.river)!).push(out);
    }
  }
  rivers.set('Imjin', [IMJIN]);
  for (const p of PICK) if (!rivers.has(p.river)) throw new Error(`no Natural Earth feature for ${p.river}`);
  const body = [...rivers].sort(([a], [b]) => a.localeCompare(b)).map(([name, lines]) => `  ${JSON.stringify(name)}: ${JSON.stringify(lines)},`).join('\n');
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, `// Generated by scripts/build-rivers.ts from Natural Earth 10m rivers and lake centrelines (public domain). Do not edit.\n\nexport const RIVER_LINES: Record<string, [number, number][][]> = {\n${body}\n};\n`);
  for (const [name, lines] of rivers) console.log(name, lines.length, 'lines', lines.reduce((a, l) => a + l.length, 0), 'points');
}

main();
